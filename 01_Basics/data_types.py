"""data_types.py
Examples of basic Python data types."""

# Numbers
integer_value = 42
float_value = 3.14
complex_value = 1 + 2j

# String
text = "Hello, Python!"

# Boolean
is_active = True
has_errors = False

# None
nothing = None

# Sequence types
numbers_list = [1, 2, 3, 4, 5]
letters_tuple = ('a', 'b', 'c')

# Mapping type
person = {
    'name': 'Alice',
    'age': 30,
    'is_student': False,
}

# Set type
unique_numbers = {1, 2, 3, 2, 1}

if __name__ == '__main__':
    print('integer_value:', integer_value)
    print('float_value:', float_value)
    print('complex_value:', complex_value)
    print('text:', text)
    print('is_active:', is_active)
    print('has_errors:', has_errors)
    print('nothing:', nothing)
    print('numbers_list:', numbers_list)
    print('letters_tuple:', letters_tuple)
    print('person:', person)
    print('unique_numbers:', unique_numbers)

